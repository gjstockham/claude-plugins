# tables.py - per-digit flavour tables for every UWP element.
#
# Each UWP element has its own sub-seed, and each VALUE of each element has
# its own table. Two worlds sharing a digit draw from the same table but
# (almost always) land on different entries, because the pick is seeded by
# the world's unique hash. Add entries freely: picks are independent per
# category, so growing a table never reshuffles other elements - though it
# MAY change future picks within this element for worlds not yet written to
# a dossier (existing dossiers are canon and unaffected).

