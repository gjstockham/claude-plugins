def clamp_pick(table, key):
    """Return the table list for key, clamping to the nearest defined value."""
    if key in table:
        return table[key]
    ks = sorted(k for k in table if isinstance(k, int))
    return table[min(ks, key=lambda k: abs(k - key))]
